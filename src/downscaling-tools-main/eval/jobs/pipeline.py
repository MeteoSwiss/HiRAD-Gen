"""Multi-job pipeline renderer with SLURM dependency chaining.

Generates per-stage sbatch scripts with correct resource profiles and a
``submit_pipeline.sh`` launcher that chains them via ``--dependency=afterok``.

Runnable as a module: ``python -m eval.jobs.pipeline --help``
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any


@dataclass
class ScriptEntry:
    name: str
    path: Path
    content: str
    dependencies: list[str] = field(default_factory=list)


@dataclass
class PipelineManifest:
    scripts: list[ScriptEntry]
    submit_script: Path
    submit_content: str
    lane: str
    host: str
    checkpoint: str


def _inject_preflight(script: str, code_root: str) -> str:
    """Insert preflight checks before the ``# Run evaluation`` marker."""
    block = (
        "\n# Preflight checks\n"
        f"source {code_root}/eval/jobs/templates/preflight_eval_check.sh\n"
        "preflight_cluster\npreflight_venv\npreflight_summary\n"
    )
    return script.replace("\n# Run evaluation", block + "\n# Run evaluation")


def _var_name(script_name: str) -> str:
    """Convert script name to SLURM variable name.

    ``02_eval_tc`` -> ``EVAL_TC_JOB``
    """
    # Strip numeric prefix (e.g. "01_" or "03_")
    stripped = re.sub(r"^\d+_", "", script_name)
    return stripped.upper() + "_JOB"


def _render_submit_script(
    manifest_scripts: list[ScriptEntry],
    lane: str,
    host: str,
    checkpoint: str,
) -> str:
    """Generate the ``submit_pipeline.sh`` dependency-chaining launcher."""
    lines = [
        "#!/bin/bash",
        "set -euo pipefail",
        "# Generated by eval/jobs/pipeline.py",
        f"# Lane: {lane} | Host: {host} | Checkpoint: {checkpoint}",
        'SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"',
        "",
    ]

    for entry in manifest_scripts:
        var = _var_name(entry.name)

        if not entry.dependencies:
            lines.append(
                f'{var}=$(sbatch --parsable "${{SCRIPT_DIR}}/{entry.name}.sbatch")'
            )
        else:
            dep_vars = ":".join(f"${{{_var_name(d)}}}" for d in entry.dependencies)
            lines.append(
                f'{var}=$(sbatch --parsable --dependency=afterok:{dep_vars} '
                f'"${{SCRIPT_DIR}}/{entry.name}.sbatch")'
            )

        # Friendly label from script name
        label = entry.name.replace("_", " ").lstrip("0123456789 ")
        lines.append(f'echo "Submitted {label}: ${{{var}}}"')
        lines.append("")

    lines.append(f'echo "Pipeline submitted. Monitor with: squeue -u $(whoami) -n eval-{lane}-*"')
    lines.append("")

    return "\n".join(lines)


def render_pipeline(
    lane: str,
    host: str,
    checkpoint: str,
    overrides: dict[str, Any] | None = None,
    split_evaluators: bool = True,
    output_dir: Path | None = None,
    eval_output_dir: str | None = None,
) -> PipelineManifest:
    """Render a full multi-job pipeline with dependency chaining.

    Parameters
    ----------
    lane : str
        Lane name (e.g. ``o96_o320``).
    host : str
        Host name (e.g. ``atos_ac``).
    checkpoint : str
        Path to the model checkpoint.
    overrides : dict | None
        Extra CLI flags passed through to each script.
    split_evaluators : bool
        If True (default), generate one sbatch per evaluator.
        If False, generate a single evaluate sbatch for all evaluators.
    output_dir : Path | None
        If given, write all scripts to this directory.
    eval_output_dir : str | None
        Shared evaluation output directory for the pipeline.
        If None, auto-generated as ``{scratch_root}/eval/{lane}/run_{timestamp}``.
        The predict step writes to ``{eval_output_dir}/predictions/``,
        the evaluate steps read from there, and scoreboard reads from
        ``{eval_output_dir}/``.

    Returns
    -------
    PipelineManifest
        Manifest of generated scripts and the submit launcher.
    """
    from datetime import datetime, timezone

    from eval.config.loader import load_host, load_lane
    from eval.jobs.renderer import render_sbatch
    from eval.jobs.resources import resolve_resources

    lane_config = load_lane(lane)
    host_config = load_host(host)
    code_root = host_config["code_root"]
    scratch_root = host_config["scratch_root"]

    # Compute shared eval output directory
    if eval_output_dir is None:
        ts = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S")
        ckpt_short = Path(checkpoint).name[:12]
        eval_output_dir = f"{scratch_root}/eval/{lane}/run_{ts}_{ckpt_short}"
    predictions_dir = f"{eval_output_dir}/predictions"

    evaluators = lane_config["evaluator_groups"]["default"]
    scripts: list[ScriptEntry] = []

    # --- 01: predict ---
    predict_resources = resolve_resources(lane_config, host_config, stage="predict")
    predict_resources["job_name_suffix"] = "-predict"
    predict_script = render_sbatch(
        lane=lane, host=host, checkpoint=checkpoint,
        mode="predict", overrides=overrides,
        resource_overrides=predict_resources,
    )
    predict_script = _inject_preflight(predict_script, code_root)
    predict_name = "01_predict"
    scripts.append(ScriptEntry(
        name=predict_name,
        path=Path(f"{predict_name}.sbatch"),
        content=predict_script,
    ))

    # --- 02: evaluate (one per evaluator or combined) ---
    eval_names: list[str] = []

    if split_evaluators:
        for evaluator in evaluators:
            eval_resources = resolve_resources(
                lane_config, host_config,
                stage="evaluate", evaluator=evaluator,
            )
            eval_resources["job_name_suffix"] = f"-eval-{evaluator}"

            cli_overrides = dict(overrides) if overrides else {}
            cli_overrides["--only"] = evaluator
            cli_overrides["--predictions-dir"] = predictions_dir

            eval_script = render_sbatch(
                lane=lane, host=host, checkpoint=checkpoint,
                mode="evaluate", overrides=cli_overrides,
                resource_overrides=eval_resources,
            )
            eval_script = _inject_preflight(eval_script, code_root)
            name = f"02_eval_{evaluator}"
            eval_names.append(name)
            scripts.append(ScriptEntry(
                name=name,
                path=Path(f"{name}.sbatch"),
                content=eval_script,
                dependencies=[predict_name],
            ))
    else:
        eval_resources = resolve_resources(
            lane_config, host_config, stage="evaluate",
        )
        eval_resources["job_name_suffix"] = "-eval"
        cli_overrides = dict(overrides) if overrides else {}
        cli_overrides["--predictions-dir"] = predictions_dir
        eval_script = render_sbatch(
            lane=lane, host=host, checkpoint=checkpoint,
            mode="evaluate", overrides=cli_overrides,
            resource_overrides=eval_resources,
        )
        eval_script = _inject_preflight(eval_script, code_root)
        name = "02_evaluate"
        eval_names.append(name)
        scripts.append(ScriptEntry(
            name=name,
            path=Path(f"{name}.sbatch"),
            content=eval_script,
            dependencies=[predict_name],
        ))

    # --- 03: scoreboard ---
    scoreboard_resources = resolve_resources(
        lane_config, host_config, stage="scoreboard",
    )
    scoreboard_resources["job_name_suffix"] = "-scoreboard"
    sb_overrides = dict(overrides) if overrides else {}
    sb_overrides["--eval-dir"] = eval_output_dir
    scoreboard_script = render_sbatch(
        lane=lane, host=host, checkpoint=checkpoint,
        mode="scoreboard", overrides=sb_overrides,
        resource_overrides=scoreboard_resources,
    )
    scoreboard_script = _inject_preflight(scoreboard_script, code_root)
    scoreboard_name = "03_scoreboard"
    scripts.append(ScriptEntry(
        name=scoreboard_name,
        path=Path(f"{scoreboard_name}.sbatch"),
        content=scoreboard_script,
        dependencies=eval_names,
    ))

    # --- submit_pipeline.sh ---
    submit_path = Path("submit_pipeline.sh")
    submit_content = _render_submit_script(scripts, lane, host, checkpoint)

    # Write files if output_dir is given
    if output_dir is not None:
        output_dir.mkdir(parents=True, exist_ok=True)
        for entry in scripts:
            (output_dir / entry.path).write_text(entry.content, encoding="utf-8")
        (output_dir / submit_path).write_text(submit_content, encoding="utf-8")
        # Make submit script executable
        submit_full = output_dir / submit_path
        submit_full.chmod(submit_full.stat().st_mode | 0o755)

    return PipelineManifest(
        scripts=scripts,
        submit_script=submit_path,
        submit_content=submit_content,
        lane=lane,
        host=host,
        checkpoint=checkpoint,
    )


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m eval.jobs.pipeline",
        description="Generate a multi-job evaluation pipeline with SLURM dependency chaining.",
    )
    parser.add_argument("--lane", required=True, help="Lane name (e.g. o96_o320)")
    parser.add_argument("--host", required=True, help="Host name (e.g. atos_ac)")
    parser.add_argument("--checkpoint", required=True, help="Path to model checkpoint")
    parser.add_argument(
        "--output-dir", default=None,
        help="Write scripts to this directory",
    )
    parser.add_argument(
        "--no-split", action="store_true",
        help="Generate a single evaluate job instead of one per evaluator",
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print manifest summary without writing files",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    parser = _build_parser()
    args = parser.parse_args(argv)

    output_dir = None
    if args.output_dir and not args.dry_run:
        output_dir = Path(args.output_dir)

    manifest = render_pipeline(
        lane=args.lane,
        host=args.host,
        checkpoint=args.checkpoint,
        split_evaluators=not args.no_split,
        output_dir=output_dir,
    )

    print(f"Pipeline: {manifest.lane} on {manifest.host}")
    print(f"Scripts: {len(manifest.scripts)}")
    for s in manifest.scripts:
        deps = f" -> deps={s.dependencies}" if s.dependencies else ""
        print(f"  {s.name}{deps}")

    if args.dry_run:
        print("\n--- submit_pipeline.sh ---")
        print(manifest.submit_content)


if __name__ == "__main__":
    main()
