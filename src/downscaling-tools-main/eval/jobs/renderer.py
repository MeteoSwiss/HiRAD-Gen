"""HPC sbatch script renderer for the evaluation framework.

Generates sbatch scripts from YAML host/lane configuration.
Runnable as a module: ``python -m eval.jobs.renderer --help``
"""

from __future__ import annotations

import argparse
import shlex
import sys
from pathlib import Path
from typing import Any


def _checkpoint_short(path: str) -> str:
    """Extract a short identifier from a checkpoint path.

    If *path* ends with ``.ckpt``, use the parent directory name;
    otherwise use the file stem.  Truncated to 20 characters.
    """
    p = Path(path)
    if p.suffix == ".ckpt":
        name = p.parent.name
    else:
        name = p.stem
    return name[:20]


def _sbatch_header(
    lane: str,
    checkpoint: str,
    scheduler: dict[str, Any],
    scratch_root: str,
    gpus: int = 0,
    ntasks_per_node: int = 1,
    job_name_suffix: str = "",
) -> str:
    """Render ``#SBATCH`` directive block."""
    short = _checkpoint_short(checkpoint)
    qos = scheduler["qos"]
    time_limit = scheduler.get("default_time", "04:00:00")
    mem = scheduler.get("default_mem", "64G")
    cpus = scheduler.get("default_cpus", 16)
    slurm_out = f"{scratch_root}/eval/_slurm/%x_%j.out"

    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name=eval-{lane}{job_name_suffix}-{short}",
        f"#SBATCH --qos={qos}",
        f"#SBATCH --time={time_limit}",
        f"#SBATCH --mem={mem}",
        f"#SBATCH --cpus-per-task={cpus}",
        "#SBATCH --nodes=1",
        f"#SBATCH --ntasks-per-node={ntasks_per_node}",
        f"#SBATCH --output={slurm_out}",
    ]

    if gpus > 0:
        lines.append(f"#SBATCH --gpus-per-node={gpus}")
    elif qos == "ng":
        lines.append("#SBATCH --gpus-per-node=0")

    return "\n".join(lines)


def _comment_block(lane: str, host: str, checkpoint: str, mode: str) -> str:
    """Render the informational comment block."""
    lines = [
        "",
        "set -euo pipefail",
        "",
        "# Generated by eval/jobs/renderer.py",
        f"# Lane: {lane}",
        f"# Host: {host}",
        f"# Checkpoint: {checkpoint}",
        f"# Mode: {mode}",
    ]
    return "\n".join(lines)


def _environment_block(
    environment_setup: dict[str, Any],
    code_root: str,
) -> str:
    """Render module loads, exports, PYTHONPATH, venv activation, and cd."""
    lines: list[str] = [""]

    # Module loads
    for mod in environment_setup.get("module_loads", []):
        lines.append(f"module load {mod}")

    lines.append("")

    # Exports from config
    for key, value in environment_setup.get("exports", {}).items():
        lines.append(f'export {key}="{value}"')

    # PYTHONPATH must include code_root
    lines.append(f'export PYTHONPATH="{code_root}:${{PYTHONPATH:-}}"')

    lines.append("")

    # Venv activation
    venv_activate = environment_setup["venv_activate"]
    lines.append(f"source {venv_activate}")

    lines.append("")

    # cd to code root
    lines.append(f"cd {code_root}")

    return "\n".join(lines)


def _post_eval_block(predictions_dir: str, evaluator: str) -> str:
    """Render post-eval canonical placement block for a single evaluator.

    Copies evaluator outputs to their canonical locations immediately after
    eval.cli completes, without waiting for a finalize step:
      - PDFs        → <run_root>/plots/
      - stats/JSON  → <run_root>/data/<evaluator_canonical>/
    """
    lines = [
        "",
        f"# Post-eval: surface {evaluator} outputs to canonical locations",
        f"PRED_DIR={shlex.quote(predictions_dir)}",
        'DATA_DIR="$(dirname "${PRED_DIR}")"',
        'RUN_ROOT="$(dirname "${DATA_DIR}")"',
        f'EVAL_OUT="${{DATA_DIR}}/evaluators/{evaluator}"',
        'mkdir -p "${RUN_ROOT}/plots"',
    ]

    if evaluator == "region_plot":
        lines += [
            'for pdf in "${EVAL_OUT}"/*.pdf; do',
            '    [[ -f "${pdf}" ]] || continue',
            '    cp "${pdf}" "${RUN_ROOT}/plots/"',
            '    echo "[PLOTS] plots/$(basename "${pdf}")"',
            'done',
        ]
    elif evaluator == "spectra":
        lines += [
            'mkdir -p "${DATA_DIR}/spectra"',
            'for f in "${EVAL_OUT}"/*.json; do',
            '    [[ -f "${f}" ]] || continue',
            '    cp "${f}" "${DATA_DIR}/spectra/"',
            '    echo "[CANON] data/spectra/$(basename "${f}")"',
            'done',
            'for pdf in "${EVAL_OUT}"/*.pdf; do',
            '    [[ -f "${pdf}" ]] || continue',
            '    cp "${pdf}" "${RUN_ROOT}/plots/"',
            '    echo "[PLOTS] plots/$(basename "${pdf}")"',
            'done',
        ]
    elif evaluator == "tc":
        lines += [
            'mkdir -p "${DATA_DIR}/tc"',
            'if [[ -f "${EVAL_OUT}/stats.json" ]]; then',
            '    cp "${EVAL_OUT}/stats.json" "${DATA_DIR}/tc/idalia__franklin.stats.json"',
            '    echo "[CANON] data/tc/idalia__franklin.stats.json"',
            'fi',
            'for pdf in "${EVAL_OUT}"/*.pdf "${EVAL_OUT}/plots"/*.pdf; do',
            '    [[ -f "${pdf}" ]] || continue',
            '    cp "${pdf}" "${RUN_ROOT}/plots/"',
            '    echo "[PLOTS] plots/$(basename "${pdf}")"',
            'done',
        ]
    elif evaluator == "surface":
        lines += [
            'if [[ -f "${EVAL_OUT}/surface_loss.json" ]]; then',
            '    cp "${EVAL_OUT}/surface_loss.json" "${DATA_DIR}/surface_loss.json"',
            '    echo "[CANON] data/surface_loss.json"',
            'fi',
        ]

    return "\n".join(lines)


def _cli_command(
    mode: str,
    checkpoint: str,
    lane: str,
    overrides: dict[str, Any] | None = None,
) -> str:
    """Render the ``python -m eval.cli`` invocation."""
    parts = [
        "",
        "# Run evaluation",
        f"python -m eval.cli {mode} \\",
    ]

    # --checkpoint is valid for run, predict, evaluate (optional) but not scoreboard
    if mode != "scoreboard":
        ckpt_quoted = shlex.quote(checkpoint)
        parts.append(f"    --checkpoint {ckpt_quoted} \\")

    # Collect override flags
    override_parts: list[str] = []
    if overrides:
        for flag, value in overrides.items():
            if isinstance(value, bool) and value:
                override_parts.append(f"    {flag} \\")
            elif not isinstance(value, bool):
                override_parts.append(f"    {flag} {shlex.quote(str(value))} \\")

    # Add override lines
    for part in override_parts:
        parts.append(part)

    # Final line: --lane (no trailing backslash)
    parts.append(f"    --lane {lane}")

    return "\n".join(parts)


def render_sbatch(
    lane: str,
    host: str,
    checkpoint: str,
    mode: str = "run",
    overrides: dict[str, Any] | None = None,
    output_path: Path | None = None,
    resource_overrides: dict[str, Any] | None = None,
) -> str:
    """Generate an sbatch script from config.

    Parameters
    ----------
    lane : str
        Lane name (e.g. ``o96_o320``).
    host : str
        Host name (e.g. ``atos_ac``).
    checkpoint : str
        Path to the model checkpoint.
    mode : str
        CLI mode — one of ``run``, ``predict``, ``evaluate``.
    overrides : dict | None
        Extra CLI flags passed through to ``eval.cli``.
        Keys are flag names (e.g. ``--only``), values are either
        strings or ``True`` for boolean flags.
    output_path : Path | None
        If given, write the script to this path.
    resource_overrides : dict | None
        SLURM resource overrides (from ``resolve_resources``).
        Keys: qos, time, mem, cpus, gpus, ntasks_per_node.
        When provided, these override host scheduler defaults.

    Returns
    -------
    str
        The complete sbatch script content.
    """
    # Import here to keep module importable even if config is missing
    from eval.config.loader import load_host

    host_cfg = load_host(host)

    if resource_overrides:
        scheduler = dict(host_cfg["scheduler"])
        scheduler["qos"] = resource_overrides.get("qos", scheduler["qos"])
        scheduler["default_time"] = resource_overrides.get("time", scheduler.get("default_time", "04:00:00"))
        scheduler["default_mem"] = resource_overrides.get("mem", scheduler.get("default_mem", "64G"))
        scheduler["default_cpus"] = resource_overrides.get("cpus", scheduler.get("default_cpus", 16))
        gpus = resource_overrides.get("gpus", 0)
        ntasks_per_node = resource_overrides.get("ntasks_per_node", 1)
        job_name_suffix = resource_overrides.get("job_name_suffix", "")
    else:
        scheduler = host_cfg["scheduler"]
        gpus = 0
        ntasks_per_node = 1
        job_name_suffix = ""

    parts = [
        _sbatch_header(
            lane, checkpoint, scheduler, host_cfg["scratch_root"],
            gpus=gpus, ntasks_per_node=ntasks_per_node,
            job_name_suffix=job_name_suffix,
        ),
        _comment_block(lane, host, checkpoint, mode),
        _environment_block(host_cfg["environment_setup"], host_cfg["code_root"]),
        _cli_command(mode, checkpoint, lane, overrides),
    ]

    # Append post-eval canonical placement for single-evaluator evaluate scripts
    if mode == "evaluate" and overrides:
        evaluator = overrides.get("--only")
        predictions_dir = overrides.get("--predictions-dir", "")
        if evaluator and predictions_dir:
            parts.append(_post_eval_block(predictions_dir, evaluator))

    parts.append("")  # trailing newline
    script = "\n".join(parts)

    if output_path is not None:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(script, encoding="utf-8")

    return script


def _build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="python -m eval.jobs.renderer",
        description="Generate sbatch scripts for the evaluation framework.",
    )
    parser.add_argument("--lane", required=True, help="Lane name (e.g. o96_o320)")
    parser.add_argument("--host", required=True, help="Host name (e.g. atos_ac)")
    parser.add_argument("--checkpoint", required=True, help="Path to model checkpoint")
    parser.add_argument(
        "--mode", default="run", choices=["run", "predict", "evaluate"],
        help="CLI mode (default: run)",
    )
    parser.add_argument("--output", default=None, help="Write script to this path")
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Print script to stdout without writing",
    )
    parser.add_argument(
        "--only", default=None,
        help="Comma-separated evaluator list (passed through to eval.cli)",
    )
    parser.add_argument(
        "--include-diagnostics", action="store_true",
        help="Include weight diagnostics (passed through to eval.cli)",
    )
    return parser


def main(argv: list[str] | None = None) -> None:
    parser = _build_parser()
    args = parser.parse_args(argv)

    # Build overrides from pass-through flags
    overrides: dict[str, Any] = {}
    if args.only:
        overrides["--only"] = args.only
    if args.include_diagnostics:
        overrides["--include-diagnostics"] = True

    # Resolve resource profile from lane + host config
    resource_overrides: dict[str, Any] | None = None
    if args.mode in ("predict", "evaluate", "scoreboard"):
        from eval.config.loader import load_host, load_lane
        from eval.jobs.resources import resolve_resources

        lane_config = load_lane(args.lane)
        host_config = load_host(args.host)
        evaluator: str | None = None
        if args.mode == "evaluate" and args.only and "," not in args.only:
            evaluator = args.only.strip()
        resource_overrides = resolve_resources(
            lane_config, host_config, stage=args.mode, evaluator=evaluator,
        )

    output_path = Path(args.output) if args.output and not args.dry_run else None

    script = render_sbatch(
        lane=args.lane,
        host=args.host,
        checkpoint=args.checkpoint,
        mode=args.mode,
        overrides=overrides if overrides else None,
        output_path=output_path,
        resource_overrides=resource_overrides,
    )

    print(script)


if __name__ == "__main__":
    main()
