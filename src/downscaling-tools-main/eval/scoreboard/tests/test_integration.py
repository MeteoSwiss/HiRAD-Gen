"""Golden-file integration tests — frozen inputs with pinned expected outputs.

These tests break the trust chain: expected values are hand-verified from
first principles, not generated by the code under test.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

GOLDEN_DIR = Path(__file__).parent / "golden"


def _load_golden(name: str) -> tuple[dict, dict]:
    """Load a golden input and expected output pair."""
    input_path = GOLDEN_DIR / f"{name}.json"
    expected_path = GOLDEN_DIR / f"{name}.expected.json"
    with input_path.open() as f:
        input_data = json.load(f)
    with expected_path.open() as f:
        expected_data = json.load(f)
    return input_data, expected_data


class TestTCGolden:
    """Golden-file tests for TC scoring."""

    def test_tc_o320_idalia_analysis_anchored(self, tmp_path):
        """Hand-verified TC scoring with explicit canonical analysis + EEFO rescaling."""
        input_data, expected_data = _load_golden("tc_o320_idalia_analysis_anchored")

        stats_path = tmp_path / "tc.stats.json"
        stats_path.write_text(json.dumps({
            "events": input_data["events"],
        }))

        from eval._backends.scoreboard.tc import load_tc_extreme_scores_from_json

        result = load_tc_extreme_scores_from_json(
            stats_path,
            run_id=input_data["run_id"],
            event_names=input_data["event_names"],
            canonical_analysis_by_event=input_data["canonical_analysis"],
        )

        expected = expected_data["expected"]
        for key, value in expected.items():
            assert result[key] == pytest.approx(value, rel=1e-9), (
                f"Score mismatch for {key}: got {result[key]}, expected {value}"
            )

    def test_tc_individual_functions_match_hand_calc(self):
        """Verify individual scoring functions match hand-calculated values."""
        from eval._backends.scoreboard.tc import (
            mslp_depth,
            multi_depth_enfo_deviation,
            multi_depth_tc_score,
            rescale_with_eefo_floor,
        )

        _, expected_data = _load_golden("tc_o320_idalia_analysis_anchored")
        hv = expected_data["hand_verification"]

        analysis = {
            "mslp_p1": 970.0, "mslp_p01": 965.0, "mslp_min": 960.0,
            "wind_p99": 30.0, "wind_p999": 35.0, "wind_max": 40.0,
        }
        model = {
            "mslp_p1": 975.0, "mslp_p01": 970.0, "mslp_min": 965.0,
            "wind_p99": 28.0, "wind_p999": 32.0, "wind_max": 36.0,
        }
        eefo = {
            "mslp_p1": 1005.0, "mslp_p01": 1003.0, "mslp_min": 1000.0,
            "wind_p99": 8.0, "wind_p999": 10.0, "wind_max": 12.0,
        }
        enfo = {
            "mslp_p1": 980.0, "mslp_p01": 975.0, "mslp_min": 970.0,
            "wind_p99": 25.0, "wind_p999": 28.0, "wind_max": 32.0,
        }

        assert mslp_depth(970.0) == pytest.approx(hv["mslp_p1_depth_analysis"])
        assert mslp_depth(975.0) == pytest.approx(hv["mslp_p1_depth_model"])

        raw = multi_depth_tc_score(model, analysis)
        assert raw == pytest.approx(hv["raw_model_score"], rel=1e-9)

        eefo_floor = multi_depth_tc_score(eefo, analysis)
        assert eefo_floor == pytest.approx(hv["eefo_floor"], rel=1e-9)

        rescaled = rescale_with_eefo_floor(raw, eefo_floor)
        assert rescaled == pytest.approx(hv["rescaled_score"], rel=1e-9)

        deviation = multi_depth_enfo_deviation(model, enfo, analysis)
        assert deviation == pytest.approx(hv["enfo_deviation"], rel=1e-9)


class TestSurfaceGolden:
    """Golden-file tests for surface scoring."""

    def test_truth_std_normalization(self, tmp_path):
        """Verify truth-std nMSE calculation matches expected values."""
        from eval._backends.scoreboard.surface import load_surface_loss_metrics

        summary = tmp_path / "surface_loss_summary.json"
        summary.write_text(json.dumps({
            "weighted_surface_mse": 10.0,
            "variables": {
                "msl": {"mean_mse": 10.0, "normalized_weight": 0.6},
                "sp": {"mean_mse": 5.0, "normalized_weight": 0.3},
                "2t": {"mean_mse": 2.0, "normalized_weight": 0.1},
            },
        }))

        result = load_surface_loss_metrics(
            summary,
            truth_std_by_variable={"msl": 10.0, "sp": 5.0, "2t": 2.0},
        )

        # Hand-calculated: msl_nmse=10/100=0.1, sp_nmse=5/25=0.2, 2t_nmse=2/4=0.5
        # weighted = 0.6*0.1 + 0.3*0.2 + 0.1*0.5 = 0.06 + 0.06 + 0.05 = 0.17
        assert result["weighted_nmse"] == pytest.approx(0.17)
        assert result["weighted_mse"] == pytest.approx(10.0)


class TestSpectraGolden:
    """Golden-file tests for spectra scoring."""

    def test_spectra_score_inversion(self):
        """Verify spectra_score is the simple 1 - relative_l2 inversion."""
        from eval._backends.scoreboard.spectra import spectra_score

        assert spectra_score(0.0) == pytest.approx(1.0)
        assert spectra_score(0.25) == pytest.approx(0.75)
        assert spectra_score(1.0) == pytest.approx(0.0)
        assert spectra_score(2.0) == pytest.approx(0.0)  # clamped at 0
